def test_description_reaches_the_header() -> None:
    bp = decode(encode(_tiny_placement(), timestamp=dotnet_ticks(0)))
    assert bp.header.description == "generated by flab2bp"
    assert bp.header.short_desc == "tiny"


def test_description_with_special_characters_survives() -> None:
    p = dataclasses.replace(_tiny_placement(), description="60/min, 100% ratio & spray")
    bp = decode(encode(p, timestamp=dotnet_ticks(0)))
    assert bp.header.description == "60/min, 100% ratio & spray"


@pytest.mark.parametrize("name,text", fixture_texts(include_dyson=False)[:3])
def test_roundtrip_detects_a_mutated_building(name: str, text: str) -> None:
    """Guards the round-trip suite itself against being vacuously true."""
    bp = decode(text)
    mutated = dataclasses.replace(
        bp,
        buildings=(dataclasses.replace(bp.buildings[0], x=bp.buildings[0].x + 1.0),)
        + bp.buildings[1:],
    )
    assert encode_blueprint(mutated) != text


def test_reserved_header_cell_is_zero() -> None:
    text = encode(_tiny_placement(), timestamp=dotnet_ticks(0))
    cells = text[len("BLUEPRINT:") : text.index('"')].split(",")
    assert cells[7] == "0"


def test_truncated_string_is_rejected() -> None:
    text = encode(_tiny_placement(), timestamp=dotnet_ticks(0))
    with pytest.raises(BlueprintFormatError):
        decode(text[: text.index('"') + 20])
